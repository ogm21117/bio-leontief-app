    c1, c2, c3 = st.columns(3)
    c1.metric("이론적 예측값 ($\hat{Y}$)", f"{predicted_hb} 개")
    c2.metric("실제 관측값 ($Y$)", f"{actual_hb} 개")
    
    if abs(residual) >= 2:
        c3.metric("계산된 잔차 ($e$)", f"{residual}", delta="🚨 이상 신호 발생", delta_color="inverse")
