    iron_input = st.sidebar.number_input("투입된 철(Iron) 개수", min_value=0, value=40)
    actual_hb = st.sidebar.number_input("실제 관측된 헤모글로빈 생산량 (Y)", min_value=0, value=7)
    
    # 레온티예프 비율 계산 (4개씩 필요하므로 4로 나눈 값 중 최소값)
